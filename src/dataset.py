import boto3
import sagemaker
import pandas as pd
import os
import json
from openai import OpenAI
from pydantic import BaseModel
import logging
from dotenv import load_dotenv

load_dotenv()

# Configure logging
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')

class City(BaseModel):
    name: str
    current_build: str

class Turn(BaseModel):
    turn: int
    cities: list[City]

class CivViBuildAnalysis(BaseModel):
        '''
        Data structure for the build_order
        and turns insights generated by LLM
        from a gameplay screenshot, following
        the prompting in generate()

        '''

        build_order: list[str]
        turns: list[Turn]

class Dataset:
    def __init__(self):
        self.s3 = boto3.client('s3')
        self.client = OpenAI()
        self.bucket = os.environ['BUCKET']
        self.images_list = self.list_images()
        
        self.raw = []
        self.cleaned = []
            
    def list_images(self):
        '''
        Creates a list of 
        all the images currently 
        available for the 
        dataset 
        '''

        response = self.s3.list_objects_v2(Bucket=self.bucket, Prefix='data/images/')
        images_list = [{"name": obj["Key"], "url": f"https://{self.bucket}.s3.amazonaws.com/{obj['Key']}"} for obj in response.get("Contents", []) if obj["Key"] != 'data/images/']

        logging.info(f"Found {len(images_list)} images.")

        return images_list

    def generate(self):
        '''
        Generates a text dataset 
        by downloading gameplay images
        one at a time and generating
        a list of the build decisions
        made by the player by city and 
        turn for CivViBuildAnalysis
        '''

        raw_text = pd.DataFrame()
        
        for idx, image in enumerate(self.images_list[:10], start=1):
            '''
            Here we create the data structure
            for the dataset.json file, before
            cleaning it and adding locally. 
            Dataset should result in the following:

            build_orders = {
                "game_id": "game_001", # example
                "build_order": [], # ordered list of all build decisions, compiled post-iteration
                "turns": [
                    {
                        "turn": 1, # example
                        "cities": [
                            {
                                "name": "city_1", # example
                                "current_build": "Settler" # example
                            }
                        ]
                    }   
                ]
            }
            '''

            game_id = image['name'][:18]
            logging.info(f"Processing image {idx} of {len(self.images_list)}, filename: {game_id}")
            completion = self.client.beta.chat.completions.parse(
                model="gpt-4o-2024-08-06",
                messages=[
                    {"role": "system", "content": os.environ['OPEN_AI_SYSTEM_PROMPT']},
                    {
                        "role": "user",
                        "content": [
                            {"type": "text", "text": "Return the data in the format of the CivViBuildAnalysis class."},
                            {
                                "type": "image_url",
                                "image_url": {
                                    "url": image['url'],
                                }
                            },
                        ],
                    },
                ],
                response_format=CivViBuildAnalysis,
            )

            event = completion.choices[0].message.parsed

            build_order = {
                "game_id": f"{game_id}",
                "build_order": [],  
                "turns": [
                    {
                        "turn": event.turns[0].turn,
                        "cities": [
                            {
                                "name": event.turns[0].cities[0].name, 
                                "current_build": event.turns[0].cities[0].current_build
                            }
                        ]
                    }
                ]
            }
            
            raw_text = raw_text.append(build_order, ignore_index=True)

            print(raw_text)
            input('')

        # add iteration into build_order compile (what if there's multiple cities?)
        # post-iteration sort turns and get build_order

        return raw_text
